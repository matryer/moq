package moq

import (
	"bytes"
	"os"
	"os/exec"
	"path/filepath"
	"testing"
)

func TestLocalTypeShadowing(t *testing.T) {
	for name, method := range map[string]string{
		"named":            "Method(s s)",
		"pointer":          "Method(s *s)",
		"slice":            "Method(s []s)",
		"other_parameter":  "Method(s int, value s)",
		"alias":            "Method(alias alias)",
		"suffix_collision": "Method(s s, sMoqParam sMoqParam)",
	} {
		t.Run(name, func(t *testing.T) {
			dir := t.TempDir()
			source := "package shadow\ntype s struct{}\ntype alias = s\ntype sMoqParam struct{}\ntype I interface { " + method + " }\n"
			for filename, content := range map[string]string{
				"go.mod":    "module example/shadow\n\ngo 1.26\n",
				"source.go": source,
			} {
				if err := os.WriteFile(filepath.Join(dir, filename), []byte(content), 0o600); err != nil {
					t.Fatal(err)
				}
			}
			m, err := New(Config{SrcDir: dir})
			if err != nil {
				t.Fatal(err)
			}
			var generated bytes.Buffer
			if err := m.Mock(&generated, "I"); err != nil {
				t.Fatal(err)
			}
			if err := os.WriteFile(filepath.Join(dir, "mock.go"), generated.Bytes(), 0o600); err != nil {
				t.Fatal(err)
			}
			cmd := exec.Command("go", "test", ".")
			cmd.Dir = dir
			if output, err := cmd.CombinedOutput(); err != nil {
				t.Fatalf("generated mock does not compile: %v\n%s", err, output)
			}
		})
	}
}
