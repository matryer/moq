package moq

import (
	"bytes"
	"os"
	"os/exec"
	"path/filepath"
	"strings"
	"testing"
)

func TestGenericConstraintEnsure(t *testing.T) {
	for _, skipEnsure := range []bool{false, true} {
		name := "ensure"
		if skipEnsure {
			name = "skip-ensure"
		}
		t.Run(name, func(t *testing.T) {
			m, err := New(Config{SrcDir: "testpackages/genericconstraints", SkipEnsure: skipEnsure})
			if err != nil {
				t.Fatal(err)
			}
			var generated bytes.Buffer
			if err := m.Mock(&generated, "Sorter", "Store"); err != nil {
				t.Fatal(err)
			}
			source, err := os.ReadFile("testpackages/genericconstraints/genericconstraints.go")
			if err != nil {
				t.Fatal(err)
			}
			dir := t.TempDir()
			for file, contents := range map[string][]byte{
				"go.mod":    []byte("module genericconstraints\n\ngo 1.26.0\n"),
				"source.go": source,
				"mock.go":   generated.Bytes(),
			} {
				if err := os.WriteFile(filepath.Join(dir, file), contents, 0o600); err != nil {
					t.Fatal(err)
				}
			}
			compile := func() ([]byte, error) {
				cmd := exec.Command("go", "test", "./...")
				cmd.Dir = dir
				return cmd.CombinedOutput()
			}
			if out, err := compile(); err != nil {
				t.Fatalf("generated code did not compile: %v\n%s", err, out)
			}
			// A broken implementation must be rejected by the ensure, even when
			// its generic function is never instantiated or called.
			broken := strings.Replace(generated.String(), ") Sort(", ") sort(", 1)
			if broken == generated.String() {
				t.Fatal("generated Sort method not found")
			}
			if err := os.WriteFile(filepath.Join(dir, "mock.go"), []byte(broken), 0o600); err != nil {
				t.Fatal(err)
			}
			out, err := compile()
			if skipEnsure && err != nil {
				t.Fatalf("skip-ensure unexpectedly checked implementation: %v\n%s", err, out)
			}
			if !skipEnsure && (err == nil || !bytes.Contains(out, []byte("missing method Sort"))) {
				t.Fatalf("ensure did not reject missing Sort method: %v\n%s", err, out)
			}
		})
	}
}
